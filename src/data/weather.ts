import type { WeatherData, HourlyPoint, DailyPoint } from "@/types";

const baseHourly = (
  startTemp: number,
  peak: number,
  rainStart: number,
  rainPeak: number,
  uvPeak: number,
): HourlyPoint[] => {
  const conds: HourlyPoint["condition"][] = [
    "clear-night", "clear-night", "partly-cloudy", "partly-cloudy", "partly-cloudy", "sunny",
    "sunny", "sunny", "partly-cloudy", "partly-cloudy", "sunny", "sunny",
    "sunny", "partly-cloudy", "cloudy", "cloudy", "rain", "rain",
    "partly-cloudy", "partly-cloudy", "cloudy", "clear-night", "clear-night", "clear-night",
  ];
  const hours = Array.from({ length: 24 }, (_, i) => i);
  return hours.map((h) => {
    const tempCurve = startTemp + (peak - startTemp) * Math.sin(((h - 6) / 12) * Math.PI);
    const temp = Math.round(Math.max(startTemp, Math.min(peak, tempCurve)));
    const rain = h >= 15 && h <= 19 ? Math.round(rainPeak - Math.abs(h - 17) * 8) : h >= rainStart ? 20 : 5;
    const uv = h >= 6 && h <= 18 ? Math.round(uvPeak * Math.sin(((h - 6) / 12) * Math.PI)) : 0;
    return {
      time: `${String(h).padStart(2, "0")}:00`,
      hour: h,
      temp,
      feelsLike: Math.round(temp + 2),
      condition: conds[h],
      rainProbability: Math.max(0, rain),
      humidity: 60 + (h < 12 ? 15 : -10) + (rain > 30 ? 15 : 0),
      wind: 8 + (h >= 14 ? 6 : 0) + (rain > 40 ? 10 : 0),
      uv: Math.max(0, uv),
    };
  });
};

const baseDaily = (high: number, low: number, rainMid: number): DailyPoint[] => {
  const days = ["Today", "Tue", "Wed", "Thu", "Fri", "Sat", "Sun"];
  const dates = ["22 Aug", "23 Aug", "24 Aug", "25 Aug", "26 Aug", "27 Aug", "28 Aug"];
  const conds: DailyPoint["condition"][] = [
    "partly-cloudy", "sunny", "cloudy", "rain", "rain", "partly-cloudy", "sunny",
  ];
  return days.map((d, i) => ({
    day: d,
    dateLabel: dates[i],
    high: Math.round(high - i * 0.5),
    low: Math.round(low + i * 0.3),
    condition: conds[i],
    rainProbability: i === 3 || i === 4 ? rainMid : i === 2 ? rainMid / 2 : 10,
  }));
};

